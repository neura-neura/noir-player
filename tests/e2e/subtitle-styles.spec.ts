import { expect, test } from '@playwright/test';

test('complete subtitle styles can be applied, saved, renamed, updated and deleted persistently', async ({ page }) => {
  await page.goto('/');
  const open = async () => {
    await page.locator('input[type=file]').first().setInputFiles('tests/fixtures/controls.mp4');
    await expect(page.locator('video')).toHaveJSProperty('readyState', 4);
    await page.locator('input[type=file]').nth(1).setInputFiles('tests/fixtures/smoke.srt');
    await page.locator('video').evaluate((video: HTMLVideoElement) => { video.pause(); video.currentTime = 0.5; });
  };
  await open();
  const library = page.getByRole('region', { name: 'Saved styles' });
  const cards = library.locator('.saved-style-apply');
  await expect(cards).toHaveCount(2);
  await expect(cards.nth(0)).toContainText('Noir Player');
  await expect(cards.nth(1)).toContainText('Anime Classic');
  await cards.nth(1).click();
  await expect(cards.nth(1)).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.caption-text')).toHaveCSS('-webkit-text-stroke-width', '4.8px');
  const outline = page.getByRole('slider', { name: 'Outline', exact: true });
  await outline.focus();
  await outline.press('End');
  await expect(page.locator('.caption-text')).toHaveCSS('-webkit-text-stroke-width', '16px');
  const anime = await page.evaluate(() => JSON.parse(localStorage.getItem('noir-web-player:subtitle-style')!));
  await library.getByLabel('Style name').fill('My anime');
  await library.getByRole('button', { name: 'Save as new' }).click();
  await cards.nth(0).click();
  await expect(cards.nth(0)).toHaveAttribute('aria-pressed', 'true');
  await library.getByRole('button', { name: /My anime/ }).click();
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('noir-web-player:subtitle-style')!))).toEqual(anime);
  await library.getByRole('button', { name: 'Rename', exact: true }).click();
  await library.getByLabel('Style name').first().fill('My cinema');
  await library.getByRole('button', { name: 'Save name', exact: true }).click();
  await cards.nth(0).click();
  await library.getByRole('button', { name: 'Save current settings' }).click();
  await expect(library.getByRole('button', { name: /My cinema/ })).toHaveAttribute('aria-pressed', 'true');
  await page.reload();
  await open();
  await expect(library.getByRole('button', { name: /My cinema/ })).toBeVisible();
  await cards.nth(1).click();
  await library.getByRole('button', { name: /My cinema/ }).click();
  await expect(cards.nth(0)).toHaveAttribute('aria-pressed', 'true');
  await library.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.reload();
  await open();
  await expect(cards).toHaveCount(2);
  await cards.nth(1).click();
  await library.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/saved-style-library.png', fullPage: true });
  await page.locator('.panel-close').click();
  await page.locator('input[type=file]').nth(1).setInputFiles({ name: 'reference.srt', mimeType: 'text/plain', buffer: Buffer.from("1\n00:00:00,100 --> 00:00:10,000\nI don't want to be the\nnice person anymore.\n") });
  await page.locator('.panel-close').click();
  await page.locator('video').evaluate((video: HTMLVideoElement) => { video.pause(); video.currentTime = 0.5; });
  await expect(page.locator('.control-panel')).toHaveCSS('opacity', '0');
  await page.screenshot({ path: 'test-results/anime-classic-style.png', fullPage: true });
  await page.locator('video').evaluate((video: HTMLVideoElement) => { video.style.filter = 'invert(1)'; });
  await page.screenshot({ path: 'test-results/anime-classic-light-background.png', fullPage: true });
});
