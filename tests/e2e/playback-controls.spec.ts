import { expect, test } from '@playwright/test';

test('playback adjustments persist and idle cursor returns only on movement', async ({ page }) => {
  await page.goto('/');
  const open = async () => {
    await page.locator('input[type=file]').first().setInputFiles('tests/fixtures/controls.mp4');
    await expect(page.locator('video')).toHaveJSProperty('readyState', 4);
    await page.locator('.panel-close').click();
  };
  await open();
  await page.keyboard.press('d');
  await expect(page.locator('video')).toHaveJSProperty('playbackRate', 1.1);
  await expect(page.locator('.playback-feedback')).toHaveText('1.1×');
  await page.reload();
  await open();
  await expect(page.locator('video')).toHaveJSProperty('playbackRate', 1.1);
  await page.getByRole('button', { name: 'Speed +0.1 (D)', exact: true }).click();
  await expect(page.locator('video')).toHaveJSProperty('playbackRate', 1.2);
  await page.keyboard.press('s');
  await expect(page.locator('video')).toHaveJSProperty('playbackRate', 1.1);
  await page.keyboard.press('r');
  await expect(page.locator('video')).toHaveJSProperty('playbackRate', 1);
  await page.keyboard.press('m');
  await expect(page.locator('video')).toHaveJSProperty('muted', true);
  await page.keyboard.press('ArrowDown');
  await expect(page.locator('video')).toHaveJSProperty('volume', 0.95);
  await expect(page.locator('video')).toHaveJSProperty('muted', false);
  await page.locator('input[type=file]').nth(1).setInputFiles('tests/fixtures/smoke.srt');
  await expect(page.getByText('Subtitles: smoke.srt', { exact: true })).toBeVisible();
  await page.locator('video').evaluate((video: HTMLVideoElement) => { video.currentTime = 0.5; });
  await expect(page.locator('.caption-text')).toHaveText('Noir Player native smoke');
  await page.keyboard.press('c');
  await expect(page.locator('.playback-feedback')).toHaveText('CC OFF');
  await expect(page.locator('.caption-text')).toHaveCount(0);
  await page.keyboard.press('c');
  await expect(page.locator('.caption-text')).toHaveText('Noir Player native smoke');
  await page.keyboard.press('Control+-');
  await expect(page.locator('.playback-feedback')).toHaveText('CC 36px');
  await page.keyboard.press('Control+Shift+=');
  await expect(page.locator('.playback-feedback')).toHaveText('CC 38px');
  const frame = page.locator('.player-frame');
  await frame.hover();
  await expect(frame).toHaveClass(/pointer-hidden/, { timeout: 4000 });
  await page.keyboard.press('d');
  await expect(frame).toHaveClass(/pointer-hidden/);
  await page.mouse.move(0, 0);
  await frame.hover();
  await expect(frame).not.toHaveClass(/pointer-hidden/);
  await page.screenshot({ path: 'test-results/playback-controls.png' });
});

test('arrow keys seek five seconds, clamp to media bounds, and show the destination', async ({ page }) => {
  await page.goto('/');
  await page.locator('input[type=file]').first().setInputFiles('tests/fixtures/controls.mp4');
  const video = page.locator('video');
  await expect(video).toHaveJSProperty('readyState', 4);
  await page.locator('.panel-close').click();
  await video.evaluate((element: HTMLVideoElement) => { element.currentTime = 10; });
  await page.keyboard.press('ArrowRight');
  await expect(video).toHaveJSProperty('currentTime', 15);
  await expect(page.locator('.playback-feedback')).toHaveText('→ 00:15');
  await page.keyboard.press('ArrowLeft');
  await expect(video).toHaveJSProperty('currentTime', 10);
  await expect(page.locator('.playback-feedback')).toHaveText('← 00:10');
  await page.keyboard.press('Control+ArrowRight');
  await expect(video).toHaveJSProperty('currentTime', 10);
  await video.evaluate((element: HTMLVideoElement) => { element.currentTime = 2; });
  await page.keyboard.press('ArrowLeft');
  await expect(video).toHaveJSProperty('currentTime', 0);
  await expect(page.locator('.playback-feedback')).toHaveText('← 00:00');
  await video.evaluate((element: HTMLVideoElement) => { element.currentTime = 18; });
  await page.keyboard.press('ArrowRight');
  await expect(video).toHaveJSProperty('currentTime', 20);
  await expect(page.locator('.playback-feedback')).toHaveText('→ 00:20');
  await page.locator('.playback-rate-controls button').first().focus();
  await page.keyboard.press('ArrowLeft');
  await expect(video).toHaveJSProperty('currentTime', 15);
});
